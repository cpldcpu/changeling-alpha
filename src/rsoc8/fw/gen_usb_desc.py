#!/usr/bin/env python3
"""Builds the USB descriptors of the HID device as ready-made data packets.

Every packet is stored as: number of bytes to send, packet identifier, data bytes, CRC-16 (low, high).
The device then sends descriptors without computing a CRC. Output:
  fw/usb_desc.h          tables for the firmware
  build/usb_desc.hex     the plain descriptor bytes, for the testbench (device, configuration, report)
usage: gen_usb_desc.py [fw dir] [build dir]"""
import os, sys

DATA0, DATA1 = 0xC3, 0x4B


def crc16(data):
    v = 0xFFFF
    for b in data:
        v ^= b
        for _ in range(8):
            v = (v >> 1) ^ 0xA001 if v & 1 else v >> 1
    return (~v) & 0xFFFF


def packets(data, first=DATA1):
    """Split into packets of 8 data bytes; identifiers alternate."""
    out, pid = [], first
    for i in range(0, max(len(data), 1), 8):
        chunk = data[i:i + 8]
        c = crc16(chunk)
        out.append([len(chunk) + 3, pid] + list(chunk) + [c & 0xFF, c >> 8])
        pid = DATA0 if pid == DATA1 else DATA1
    return out


REPORT = [0x06, 0x00, 0xFF,        # usage page: vendor defined
          0x09, 0x01,              # usage 1
          0xA1, 0x01,              # collection: application
          0x09, 0x02,              #   usage 2
          0x15, 0x00,              #   logical minimum 0
          0x26, 0xFF, 0x00,        #   logical maximum 255
          0x75, 0x08,              #   report size 8 bits
          0x95, 0x08,              #   report count 8
          0x81, 0x02,              #   input (data, variable, absolute)
          0x91, 0x02,              #   output (data, variable, absolute): 8 bytes, SET_REPORT
          0xC0]                    # end collection
DEVICE = [18, 1, 0x10, 0x01, 0, 0, 0, 8,          # USB 1.1, class in the interface, 8 bytes on endpoint 0
          0x09, 0x12, 0x01, 0x00,                  # vendor 0x1209 (pid.codes), product 0x0001 (test)
          0x00, 0x01, 0, 0, 0, 1]                  # device release 1.00, no strings, one configuration
CONFIG = [9, 2, 34, 0, 1, 1, 0, 0x80, 50,         # configuration: 34 bytes in all, one interface, bus powered, 100 mA
          9, 4, 0, 0, 1, 3, 0, 0, 0,               # interface 0: one endpoint, class HID
          9, 0x21, 0x11, 0x01, 0, 1, 0x22, len(REPORT), 0,   # HID 1.11, one report descriptor
          7, 5, 0x81, 3, 8, 0, 10]                 # endpoint 1 IN, interrupt, 8 bytes, every 10 ms
assert len(DEVICE) == 18 and len(CONFIG) == 34

TABLES = [("usb_pk_device", packets(DEVICE)),
          ("usb_pk_config", packets(CONFIG)),
          ("usb_pk_config9", packets(CONFIG[:9])),
          ("usb_pk_report", packets(REPORT)),
          ("usb_pk_zero", packets([])),            # data packet without data, DATA1: status stage
          ("usb_pk_status", packets([0, 0])),
          ("usb_pk_val", packets([0]) + packets([1]))]     # one data byte 0 or 1: GET_CONFIGURATION, GET_IDLE, GET_PROTOCOL      # answer to GET_STATUS

fw = sys.argv[1] if len(sys.argv) > 1 else os.path.dirname(os.path.abspath(__file__))
build = sys.argv[2] if len(sys.argv) > 2 else os.path.join(fw, "..", "build")
with open(os.path.join(fw, "usb_desc.h"), "w") as f:
    f.write("/* generated by gen_usb_desc.py: descriptors as data packets with their CRC-16.\n"
            "   Each packet: number of bytes to send, packet identifier, data, CRC low, CRC high. */\n")
    f.write("/* USB_DESC_EXTERN: tables are in another image (core 1 code memory), only declared here.\n"
            "   Otherwise USB_DESC_STORAGE (default static) is put in front of every table. */\n"
            "#ifndef USB_DESC_STORAGE\n#define USB_DESC_STORAGE static\n#endif\n")
    for name, pk in TABLES:
        flat = [b for p in pk for b in p]
        f.write("#define %s_N %d\n" % (name.upper(), len(pk)))
        f.write("#ifdef USB_DESC_EXTERN\nextern const uint8_t %s[%d];\n#else\n" % (name, len(flat)))
        f.write("USB_DESC_STORAGE const uint8_t %s[%d] = {\n" % (name, len(flat)))
        for p in pk:
            f.write("    " + ", ".join("0x%02X" % b for b in p) + ",\n")
        f.write("};\n#endif\n")
    f.write("#define USB_LEN_DEVICE %d\n#define USB_LEN_CONFIG %d\n#define USB_LEN_REPORT %d\n" % (len(DEVICE), len(CONFIG), len(REPORT)))
    z8 = packets([0] * 8)[0]
    f.write("/* report packet with 8 zero bytes: first value of the input report */\n#define USB_PK_ZERO8 %s\n" % ", ".join("0x%02X" % b for b in z8))
os.makedirs(build, exist_ok=True)
with open(os.path.join(build, "usb_desc.hex"), "w") as f:
    for b in DEVICE + CONFIG + REPORT:
        f.write("%02x\n" % b)
print("descriptors: device %d, configuration %d, report %d bytes; packet tables %d bytes"
      % (len(DEVICE), len(CONFIG), len(REPORT), sum(len(b) for _, pk in TABLES for b in pk)))
